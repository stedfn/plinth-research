def test_a_reused_loaded_run_does_not_lose_index_entries(
    built_run: Built, tmp_path: Path
) -> None:
    """Four adds, the last two sharing one snapshot, must leave four acquisitions.

    Atomic file replacement makes each write all-or-nothing; it does not make
    read-modify-write atomic. No concurrency is involved -- this is one process
    holding a stale ``LoadedRun``.
    """
    stale = built_run.run
    for index in range(2):
        stale, _, _ = arc.add_artifact(
            stale,
            write(tmp_path / f"seq{index}.pdf", PDF_BYTES + str(index).encode()),
            source_id="src-seq",
            acquisition_mode=AcquisitionMode.HTTP_DOWNLOAD,
            media_type="application/pdf",
            retrieved_at=RETRIEVED_AT,
        )
    snapshot = stale
    for index in range(2, 4):
        arc.add_artifact(
            snapshot,
            write(tmp_path / f"seq{index}.pdf", PDF_BYTES + str(index).encode()),
            source_id="src-seq",
            acquisition_mode=AcquisitionMode.HTTP_DOWNLOAD,
            media_type="application/pdf",
            retrieved_at=RETRIEVED_AT,
        )
    on_disk = arc.load_run(built_run.run.root)
    added = [
        record for record in on_disk.index.acquisitions if record.source_id == "src-seq"
    ]
    assert len(added) == 4
    assert len({record.acquisition_id for record in added}) == 4


