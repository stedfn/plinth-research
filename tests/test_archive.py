def archive_state(built: Built) -> tuple[tuple[str, ...], bytes]:
    """Every blob name and the index bytes -- the whole of what an add may change.

    Compared against the run's **prior** state rather than against an empty
    archive: an empty-``blobs/`` assertion only proves anything on a fresh run,
    and this fixture has three artifacts in it already.
    """
    return (
        tuple(sorted(entry.name for entry in built.run.blobs_dir.iterdir())),
        built.run.index_path.read_bytes(),
    )


@pytest.mark.parametrize(
    ("overrides", "match"),
    [
        ({"acquisition_mode": "NOPE"}, "not an acquisition mode"),
        ({"media_type": "pdf"}, "type/subtype"),
        ({"retrieved_at": "last Tuesday"}, "ISO-8601"),
        ({"retrieved_at": 1700000000}, "ISO-8601"),
        ({"attempted_at": "2027-01-01T00:00:00Z"}, "A2"),
        ({"source_id": "not a record id"}, "source_id"),
        ({"page_count": 0}, "page_count"),
        ({"operator": "", "acquisition_mode": AcquisitionMode.MANUAL_UPLOAD}, "operator"),
        ({"url": "http://[malformed"}, "not a parseable URL"),
    ],
    ids=[
        "mode", "media-type", "unparseable-time", "epoch-time", "retrieval-before-attempt",
        "source-id", "page-count", "blank-operator", "malformed-url",
    ],
)
def test_a_predictable_mistake_leaves_the_archive_untouched(
    built_run: Built, tmp_path: Path, overrides: dict, match: str
) -> None:
    """A mistyped flag used to cost an orphan blob.

    Each of these failed at model construction, which ran *after* the bytes were
    already archived -- so ``--retrieved-at "last Tuesday"`` wrote a blob and
    then refused to record it.
    """
    before = archive_state(built_run)
    with pytest.raises(arc.ArchiveError, match=match):
        add(built_run, write(tmp_path / "candidate.pdf", PDF_BYTES + b"candidate"), **overrides)
    assert archive_state(built_run) == before


def test_the_preflight_does_not_restate_the_models(built_run: Built, tmp_path: Path) -> None:
    """The preflight runs the real constructors, so it cannot drift from them.

    ``A2`` is the witness: nothing in ``add_artifact`` knows that retrieval must
    follow its attempt, and the preflight catches it anyway.
    """
    before = archive_state(built_run)
    with pytest.raises(arc.ArchiveError, match="retrieved_at is earlier than attempted_at"):
        add(
            built_run,
            write(tmp_path / "candidate.pdf", PDF_BYTES + b"candidate"),
            attempted_at=RETRIEVED_AT + timedelta(days=1),
        )
    assert archive_state(built_run) == before


def test_a_valid_add_still_records_what_it_archived(built_run: Built, tmp_path: Path) -> None:
    """The preflight is a throwaway: the stored record carries the real digest."""
    _, acquisition, artifact = add(
        built_run, write(tmp_path / "real.pdf", PDF_BYTES + b"real"), page_count=12
    )
    assert artifact.sha256 != arc.PREFLIGHT_DIGEST
    assert acquisition.artifact_sha256 == artifact.sha256
    assert artifact.byte_length == len(PDF_BYTES) + 4
    assert artifact.page_count == 12


