def test_automatic_text_is_derived_from_the_archived_bytes(
    built_run: Built, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """``RAW_DECODE_TOOL`` claims the text is a decode of the archived bytes.

    Re-reading the source file to build it would make that claim false the
    moment the file changed between the two reads: the digest would bind one
    document while every locator resolved against another.
    """
    source = write(tmp_path / "doc.txt", "original content\n")
    real = arc._archive_blob
    seen: list[Path] = []

    def spy(path, blobs_dir, **kwargs):
        result = real(path, blobs_dir, **kwargs)
        seen.append(path)
        if len(seen) == 1:
            source.write_text("REPLACED after the raw blob landed\n", encoding="utf-8")
        return result

    monkeypatch.setattr(arc, "_archive_blob", spy)
    _, _, artifact = add(built_run, source, media_type="text/plain")

    assert seen[1] != source
    assert artifact.text_sha256 == artifact.sha256
    text_blob = blob(built_run, f"{artifact.text_sha256}{arc.TEXT_BLOB_SUFFIX}")
    assert text_blob.read_text(encoding="utf-8") == "original content\n"


def test_a_blob_is_hashed_and_decoded_from_one_read(built_run: Built) -> None:
    """Two reads of one path can straddle a change and pair an old digest with new text."""
    name = f"{built_run.text_a_sha}{arc.TEXT_BLOB_SUFFIX}"
    store = arc.BlobStore(built_run.run.blobs_dir)
    first = store.read(name)
    assert hashlib.sha256(first.text.encode("utf-8")).hexdigest() == first.sha256

    overwrite_blob(blob(built_run, name), b"different text entirely\n")
    assert store.read(name) == first, "a cached blob must not silently re-read"

    fresh = arc.BlobStore(built_run.run.blobs_dir).read(name)
    assert hashlib.sha256(fresh.text.encode("utf-8")).hexdigest() == fresh.sha256


