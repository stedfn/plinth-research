"""Gates for the run directory: archiving bytes, and the ``D`` rules over them.

One run, built in ``tmp_path`` from **generated** bytes, plus one mutation per
rule -- the same shape as ``test_models.py``, and for the same reason: a fixture
carrying every failure mode would be unreadable and would still not prove the
failures are caught.

**No PDF files anywhere.** Plinth parses no PDFs, which is a direct dividend of
the no-extraction design, so the "PDF" in this file is nine bytes of header and
some filler. ``pack-ousg-backing-006.json`` is untouched: it is the pure layer's
fixture, its digests are deliberately fake, and the point of keeping the pure
layer pure is that those two facts do not conflict.

Building the run from generated bytes rather than committing a run directory is
also what closes the "archived bytes absent in CI" hole -- ``runs/`` is
git-ignored, and nothing here reads anything that is not written first.

Each mutation asserts **the target code is present**, not that it is the only
error: one field change legitimately trips two rules, and "and no other error"
assertions turn every future rule into a broken test.
"""

