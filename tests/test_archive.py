# a known gap, pinned so nobody reads C3 as more than it is
# --------------------------------------------------------------------------


def test_an_unattempted_route_marked_completed_still_unlocks_missing(
    built_run: Built,
) -> None:
    """Documents a known gap, not desired behaviour. Closed in C4/C5.

    ``X2`` computes ``unfinished = [r for r in required if r.status is not
    COMPLETED]`` and errors if any -- so ``COMPLETED`` **unlocks** a ``MISSING``
    claim and ``BLOCKED`` prevents it. Nothing ties a ``COMPLETED`` route to an
    archived acquisition on any of its sources, so a route that was never
    attempted at all satisfies X2 and licenses the strong claim: *the declared
    search was completed and found nothing*.

    It is accepted here because C3 cannot close it. Doing so needs three pieces
    together -- routes pinned in run configuration, attested non-``ACQUIRED``
    outcomes in the index, and a completion link from a ``COMPLETED`` route to
    an index-backed acquisition on one of its sources. Shipping the first alone
    only narrows the hole, since ``status`` stays model-authored; shipping the
    third without the second would false-reject an honest "searched, found
    nothing". The adversary that would exploit this -- the extraction model --
    does not exist until C4.

    **This test asserts the gap, so changing the behaviour should break it.**
    When C4 or C5 closes it, delete this test and write its opposite.
    """
    document = mutated(built_run)
    document["sources"].append(
        {
            "source_id": "src-unsearched",
            "title": "A repository no one opened",
            "source_type": "regulatory_filing",
            "disposition": "IN_SCOPE",
        }
    )
    document["routes"].append(
        {
            "route_id": "route-never-run",
            "description": "Search the filing repository for a reserve attestation.",
            "acquisition_mode": "HTTP_DOWNLOAD",
            "status": "COMPLETED",
            "required_for_check_ids": ["PF-BACKING-006"],
            "source_ids": ["src-unsearched"],
        }
    )
    pack = constructed(built_run, document)

    # No acquisition anywhere names that source: the search never happened.
    assert not [a for a in pack.acquisitions if a.source_id == "src-unsearched"]
    assert_clean(arc.validate_pack_against_run(pack, built_run.run))

    # And X2 accepts the MISSING claim that rests on it.
    from plinth.models import Assessment
    from plinth.validate import validate_assessment_against_pack

    assessment = Assessment.model_validate(
        {
            "schema_version": "plinth.assessment/1",
            "meta": {
                "campaign_run_id": pack.campaign.run_id,
                "framework_version": "v0.2-working",
                "catalogue_sha256": built_run.run.manifest.catalogue_sha256,
                "evidence_pack_sha256": canonical_sha256(pack),
                "generated_at": moment(GENERATED_AT),
            },
            "checks": [
                {
                    "check_id": "PF-BACKING-006",
                    "applicability": "APPLIES",
                    "applicability_basis": "The product holds reserves.",
                    "applicability_observation_ids": ["OBS_001"],
                    "coverage": "MISSING",
                    "coverage_basis": "The declared search completed and found nothing.",
                    "finding": "No reserve attestation was published.",
                    "gap": {
                        "question": "Is the reserve independently attested?",
                        "what_is_known": "The issuer describes a custodian relationship.",
                        "what_remains_unresolved": "No independent attestation was found.",
                        "what_this_means": "Backing rests on issuer statement alone.",
                        "what_would_close_it": "An attestation from the custodian's auditor.",
                        "evidence": "The filing repository search returned nothing.",
                    },
                }
            ],
        }
    )
    assert_clean(validate_assessment_against_pack(assessment, pack))
