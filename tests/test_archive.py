def test_d2_one_flipped_byte_is_caught_and_the_pure_layer_cannot_see_it(
    built_run: Built,
) -> None:
    """The commit's thesis, in one test.

    (a) ``validate_pack`` still returns **clean** -- the C2 hole was real, not
    hypothetical: a pack whose archived bytes have been altered is internally
    perfect, because nothing in the pure layer ever opens a file.

    (b) ``validate_pack_against_run`` reports ``D2`` and names the artifact.

    The flip preserves length on purpose, so ``D3`` cannot be what catches it.
    """
    path = blob(built_run, f"{built_run.sha_a}.pdf")
    before = path.stat().st_size
    flip_first_byte(path)
    assert path.stat().st_size == before

    pack, problems = validate_pack(built_run.pack_doc)
    assert_clean(problems)

    issues = arc.validate_pack_against_run(pack, built_run.run)
    assert_code(issues, "D2")
    assert built_run.sha_a in rendered(issues)


