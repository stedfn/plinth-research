def rendered(issues) -> str:
    return "\n".join(issue.render() for issue in issues)


def codes(issues) -> list[str]:
    return sorted({issue.code for issue in issues})


def assert_code(issues, code: str) -> None:
    assert code in codes(issues), f"expected {code}; got:\n{rendered(issues) or '  (no issues)'}"


def assert_clean(issues) -> None:
    assert not issues, f"expected no issues; got:\n{rendered(issues)}"


def constructed(built: Built, document: dict) -> EvidencePack:
    pack, problems = validate_pack(document)
    assert pack is not None, rendered(problems)
    assert_clean(problems)
    return pack


def run_issues(built: Built, document: dict | None = None):
    """Validate a pack on its own, then against the run it belongs to."""
    pack = constructed(built, document if document is not None else built.pack_doc)
    return arc.validate_pack_against_run(pack, built.run)


def mutated(built: Built) -> dict:
    return copy.deepcopy(built.pack_doc)


def artifact_of(document: dict, sha256: str) -> dict:
    return next(record for record in document["artifacts"] if record["sha256"] == sha256)


def locator_of(document: dict, locator_id: str) -> dict:
    return next(
        record for record in document["locator_catalog"] if record["locator_id"] == locator_id
    )


def blob(built: Built, name: str) -> Path:
    return built.run.blobs_dir / name


def overwrite_blob(path: Path, payload: bytes) -> None:
    """Edit an archived blob the way a corruption or a hand edit would."""
    path.chmod(0o644)
    path.write_bytes(payload)
    path.chmod(0o444)


def flip_first_byte(path: Path) -> None:
    payload = bytearray(path.read_bytes())
    payload[0] ^= 0x01
    overwrite_blob(path, bytes(payload))


