def test_the_built_run_validates_against_itself(built_run: Built) -> None:
    assert_clean(run_issues(built_run))


def test_a_quote_spanning_a_line_break_resolves(built_run: Built) -> None:
    """The whole point of ``collapse_whitespace``, pinned.

    ``WRAPPED_QUOTE`` appears in ``TEXT_A`` only with a newline inside it. If
    this ever fails, D10 has stopped tolerating line wrapping -- and since line
    wrapping is an artifact of extraction rather than of the document, honest
    quotes would start being rejected at a rate that makes the whole check read
    as noise.
    """
    assert WRAPPED_QUOTE not in TEXT_A
    assert arc.collapse_whitespace(WRAPPED_QUOTE) in arc.collapse_whitespace(TEXT_A)
    assert_clean(run_issues(built_run))


