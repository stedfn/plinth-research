PDF_BYTES = b"%PDF-1.7\n" + bytes(range(256)) * 40
OTHER_PDF_BYTES = b"%PDF-1.7\n" + bytes(range(255, -1, -1)) * 40

# Wrapped mid-sentence on purpose: "Example Trust Company in a segregated
# account." spans the line break, and matching it is what pins the one
# normalization `collapse_whitespace` performs.
TEXT_A = (
    "OUSG product documentation\n"
    "Reserve assets are held with Example Trust\n"
    "Company in a segregated account.\n"
)
WRAPPED_QUOTE = "Example Trust Company in a segregated account."

TEXT_B = "Closing balance, 31 August 2026: USD 42,000,000.00\n"

NOW = datetime.now(UTC)
RETRIEVED_AT = NOW - timedelta(hours=1)
CUTOFF = NOW - timedelta(days=1)
GENERATED_AT = NOW + timedelta(hours=1)


def moment(value: datetime) -> str:
    return value.isoformat()


def as_json(model) -> dict:
    """The record exactly as the canonical form spells it.

    Tests build the pack from this rather than from hand-written JSON, because
    ``D6`` is precisely the rule that the pack copies the index verbatim: a
    hand-written record would be testing the test author's transcription.
    """
    return json.loads(canonical_bytes(model))


def campaign_document(run_id: str = "run-archive-001") -> dict:
    return {
        "run_id": run_id,
        "subject": "OUSG",
        "subject_description": "A generated subject for the archive tests.",
        "cutoff": moment(CUTOFF),
        "declared_acquisition_modes": ["HTTP_DOWNLOAD", "MANUAL_UPLOAD"],
        "declared_scope_note": "Generated bytes only.",
        "bounded_public_evidence": True,
    }


@dataclass
class Built:
    """A run on disk, and a pack that validates against it."""

    run: arc.LoadedRun
    pack_doc: dict
    runs_root: Path
    sha_a: str
    sha_b: str
    sha_c: str
    text_a_sha: str


def write(path: Path, payload: bytes | str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(payload, str):
        path.write_text(payload, encoding="utf-8")
    else:
        path.write_bytes(payload)
    return path


